CREATE TABLE IF NOT EXISTS saga_outbox (
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(36) NOT NULL UNIQUE,
  order_id BIGINT NOT NULL,
  payload TEXT NOT NULL,
  sent BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS saga_inbox (event_id VARCHAR(36) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id VARCHAR(200) NOT NULL,
  tenant VARCHAR(80) NOT NULL,
  amount NUMERIC(12,2) NOT NULL,
  status VARCHAR(30) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  request_key VARCHAR(80) NOT NULL UNIQUE,
  request_payload TEXT NOT NULL,
  reason VARCHAR(200)
);
